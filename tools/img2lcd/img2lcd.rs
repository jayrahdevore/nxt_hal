//! Host-side tool: packs a 100x64 ASCII PBM (P1) into the NXT LCD's
//! framebuffer layout and prints it as a Rust `static`.
//!
//! Layout (matches `nxt_hal::lcd`): 8 pages x 100 columns; byte
//! `page * 100 + x` holds the 8 vertically adjacent pixels of column `x`,
//! bit 0 = topmost row of the page, 1 = dark. PBM's 1 = black maps straight
//! onto it.
//!
//! Usage: img2lcd <in.pbm> <STATIC_NAME>   (writes Rust source to stdout)
//! Test:  rustc --test tools/img2lcd/img2lcd.rs -o /tmp/img2lcd-test && /tmp/img2lcd-test

use std::fmt::Write as _;

const WIDTH: usize = 100;
const HEIGHT: usize = 64;

/// Parses a plain (P1) PBM. Returns `(width, height, pixels)`, row-major,
/// `true` = black. Accepts `#` comments and pixels with or without
/// separating whitespace.
fn parse_p1(text: &str) -> Result<(usize, usize, Vec<bool>), String> {
    let stripped: String = text
        .lines()
        .map(|l| l.split('#').next().unwrap_or(""))
        .collect::<Vec<_>>()
        .join("\n");
    let mut rest = stripped.trim_start();
    let mut header = [0usize; 2];
    rest = rest.strip_prefix("P1").ok_or("not a plain PBM (missing P1)")?;
    for slot in &mut header {
        rest = rest.trim_start();
        let end = rest.find(|c: char| !c.is_ascii_digit()).unwrap_or(rest.len());
        *slot = rest[..end].parse().map_err(|_| "bad PBM dimensions")?;
        rest = &rest[end..];
    }
    let [w, h] = header;
    let pixels: Vec<bool> = rest
        .chars()
        .filter(|c| !c.is_whitespace())
        .map(|c| match c {
            '1' => Ok(true),
            '0' => Ok(false),
            other => Err(format!("unexpected pixel character {other:?}")),
        })
        .collect::<Result<_, _>>()?;
    if pixels.len() != w * h {
        return Err(format!("expected {} pixels, found {}", w * h, pixels.len()));
    }
    Ok((w, h, pixels))
}

/// Packs row-major pixels into page/column bytes. `height` must be a
/// multiple of 8.
fn pack(width: usize, height: usize, pixels: &[bool]) -> Vec<u8> {
    assert_eq!(height % 8, 0);
    assert_eq!(pixels.len(), width * height);
    let mut out = vec![0u8; width * height / 8];
    for page in 0..height / 8 {
        for x in 0..width {
            let mut byte = 0u8;
            for bit in 0..8 {
                if pixels[(page * 8 + bit) * width + x] {
                    byte |= 1 << bit;
                }
            }
            out[page * width + x] = byte;
        }
    }
    out
}

fn render(name: &str, bytes: &[u8]) -> String {
    let mut s = String::new();
    writeln!(s, "// @generated by tools/img2lcd from assets/rustacean-flat-happy.svg; do not edit.").unwrap();
    writeln!(s, "pub static {name}: [u8; {}] = [", bytes.len()).unwrap();
    for row in bytes.chunks(16) {
        let line: Vec<String> = row.iter().map(|b| format!("0x{b:02x}")).collect();
        writeln!(s, "    {},", line.join(", ")).unwrap();
    }
    writeln!(s, "];").unwrap();
    s
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    if args.len() != 3 {
        eprintln!("usage: img2lcd <in.pbm> <STATIC_NAME>");
        std::process::exit(2);
    }
    let text = std::fs::read_to_string(&args[1]).unwrap_or_else(|e| {
        eprintln!("img2lcd: {}: {e}", args[1]);
        std::process::exit(1);
    });
    let (w, h, pixels) = parse_p1(&text).unwrap_or_else(|e| {
        eprintln!("img2lcd: {e}");
        std::process::exit(1);
    });
    if (w, h) != (WIDTH, HEIGHT) {
        eprintln!("img2lcd: expected {WIDTH}x{HEIGHT}, got {w}x{h}");
        std::process::exit(1);
    }
    print!("{}", render(&args[2], &pack(w, h, &pixels)));
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn packs_top_bit_first_per_column() {
        // 2 wide x 8 tall: column 0 = only top pixel, column 1 = only bottom.
        let mut px = vec![false; 16];
        px[0] = true; // row 0, x 0
        px[7 * 2 + 1] = true; // row 7, x 1
        assert_eq!(pack(2, 8, &px), vec![0x01, 0x80]);
    }

    #[test]
    fn second_page_follows_first() {
        // 1 wide x 16 tall: row 8 (first row of page 1) and row 9 set.
        let mut px = vec![false; 16];
        px[8] = true;
        px[9] = true;
        assert_eq!(pack(1, 16, &px), vec![0x00, 0x03]);
    }

    #[test]
    fn parses_spaced_unspaced_and_comments() {
        let (w, h, px) = parse_p1("P1\n# comment\n3 2\n1 0 1\n010\n").unwrap();
        assert_eq!((w, h), (3, 2));
        assert_eq!(px, vec![true, false, true, false, true, false]);
    }

    #[test]
    fn rejects_wrong_pixel_count() {
        assert!(parse_p1("P1\n2 2\n1 0 1\n").is_err());
    }

    #[test]
    fn renders_static_with_length() {
        let s = render("X", &[0x01, 0xff]);
        assert!(s.contains("pub static X: [u8; 2] = ["));
        assert!(s.contains("0x01, 0xff,"));
    }
}
